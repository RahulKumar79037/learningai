import { Router } from 'express';
import { AIService } from '../services/ai.service.js';
import { authenticate, AuthenticatedRequest } from '../middleware/authMiddleware.js';
import mongoose from 'mongoose';
import {
  FlashcardDecksRepo,
  FlashcardsRepo,
  FlashcardReviewsRepo,
  SubjectsRepo,
  TopicsRepo,
  NotesRepo,
  DocumentsRepo,
  DocumentChunksRepo,
  ProgressRepo,
  LearningActivitiesRepo,
} from '../models/repositories.js';
import { MongoFlashcardModel, MongoFlashcardDeckModel } from '../models/mongooseSchemas.js';

const router = Router();

// GET /api/flashcards/decks
router.get('/decks', authenticate, (req: AuthenticatedRequest, res, next) => {
  try {
    const decks = FlashcardDecksRepo.find(d => d.userId === req.user!._id)
      .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt));

    const enriched = decks.map(deck => {
      const cardCount = FlashcardsRepo.count(c => c.deckId === deck._id);
      const learnedCount = FlashcardsRepo.count(c => c.deckId === deck._id && c.learned);
      const now = new Date().toISOString();
      const dueCount = FlashcardsRepo.count(c => c.deckId === deck._id && (!c.nextReviewDate || c.nextReviewDate <= now));
      return { ...deck, cardCount, learnedCount, dueCount };
    });

    res.json({ success: true, data: { decks: enriched } });
  } catch (err) {
    next(err);
  }
});

// GET /api/flashcards/decks/:id
router.get('/decks/:id', authenticate, (req: AuthenticatedRequest, res, next) => {
  try {
    const deck = FlashcardDecksRepo.findById(req.params.id);
    if (!deck || deck.userId !== req.user!._id) {
      return res.status(404).json({ success: false, error: 'Flashcard deck not found.' });
    }

    const cards = FlashcardsRepo.find(c => c.deckId === deck._id)
      .sort((a, b) => a.box - b.box);

    res.json({ success: true, data: { deck, cards } });
  } catch (err) {
    next(err);
  }
});

