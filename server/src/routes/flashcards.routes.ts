// POST /api/flashcards/decks/generate (AI Generate Deck)
router.post('/decks/generate', authenticate, async (req: AuthenticatedRequest, res, next) => {
  try {
    const { subjectId, topicId, documentId, noteId, cardCount = 6 } = req.body;

    let contentToAnalyze = '';
    let deckTitle = 'AI Flashcard Deck';
    let deckDesc = 'Generated by Learning Companion AI';

    if (topicId) {
      const top = TopicsRepo.findById(topicId);
      if (top) {
        deckTitle = `${top.title} Mastery Cards`;
        deckDesc = `Key concepts and definitions for ${top.title}`;
        contentToAnalyze = `${top.definition}\n${top.detailedExplanation}\nKey Concepts: ${top.importantConcepts.join(', ')}\nCommon Mistakes: ${top.commonMistakes.join(', ')}`;
      }
    } else if (noteId) {
      const note = NotesRepo.findById(noteId);
      if (note && note.userId === req.user!._id) {
        deckTitle = `${note.title} Flashcards`;
        contentToAnalyze = note.content;
      }
    } else if (documentId) {
      const doc = DocumentsRepo.findById(documentId);
      if (doc && doc.userId === req.user!._id) {
        deckTitle = `${doc.originalName} Flashcards`;
        const chunks = DocumentChunksRepo.find(c => c.documentId === doc._id)
          .sort((a, b) => a.chunkIndex - b.chunkIndex);
        if (chunks.length > 0) {
          contentToAnalyze = chunks.map(c => c.content).join('\n\n').substring(0, 10000);
        } else {
          contentToAnalyze = doc.extractedTextSample || '';
        }
      }
    } else if (subjectId) {
      const sub = SubjectsRepo.findById(subjectId);
      if (sub) {
        deckTitle = `${sub.name} Core Flashcards`;
        const topics = TopicsRepo.find(t => t.subjectId === sub._id).slice(0, 3);
        contentToAnalyze = topics.map(t => `${t.title}: ${t.definition} ${t.summary}`).join('\n\n');
      }
    }

    if (!contentToAnalyze || contentToAnalyze.trim().length === 0) {
      contentToAnalyze = 'Computer science core principles, algorithms, complexity bounds, memory management, and network protocols.';
    }

    // Call Gemini
    const generatedCards = await AIService.generateFlashcards(contentToAnalyze, Number(cardCount) || 5);

    // Create Deck
    const newDeck = FlashcardDecksRepo.insertOne({
      _id: 'deck_' + Math.random().toString(36).substring(2, 9) + Date.now().toString(36),
      userId: req.user!._id,
      title: deckTitle,
      description: deckDesc,
      subjectId,
      topicId,
      sourceDocumentId: documentId,
      cardCount: generatedCards.length,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    });

    // Insert Cards
    const insertedCards = generatedCards.map((c, i) => {
      return FlashcardsRepo.insertOne({
        _id: `card_${newDeck._id}_${i}`,
        deckId: newDeck._id,
        userId: req.user!._id,
        question: c.question,
        answer: c.answer,
        explanation: c.explanation,
        example: c.example,
        subjectId,
        topicId,
        difficulty: c.difficulty || 'medium',
        box: 0,
        reviewCount: 0,
        nextReviewDate: new Date().toISOString(),
        learned: false,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });
    });

    LearningActivitiesRepo.insertOne({
      _id: 'act_' + Date.now().toString(36),
      userId: req.user!._id,
      activityType: 'flashcard_review',
      title: `Generated ${insertedCards.length} Flashcards: ${deckTitle}`,
      timestamp: new Date().toISOString(),
    });

    res.status(201).json({
      success: true,
      data: { deck: newDeck, cards: insertedCards },
      message: 'Flashcards generated successfully!',
    });
  } catch (err) {
    next(err);
  }
});

// POST /api/flashcards/decks/:id/cards (Add Card Manually)
router.post('/decks/:id/cards', authenticate, async (req: AuthenticatedRequest, res, next) => {
  try {
    const deck = FlashcardDecksRepo.findById(req.params.id);
    if (!deck || deck.userId !== req.user!._id) {
      return res.status(404).json({ success: false, error: 'Deck not found.' });
    }

    const { question, answer, explanation, example, difficulty = 'medium' } = req.body;
    if (!question || typeof question !== 'string' || !question.trim()) {
      return res.status(400).json({ success: false, error: 'Question (card front) is required.' });
    }
    if (!answer || typeof answer !== 'string' || !answer.trim()) {
      return res.status(400).json({ success: false, error: 'Answer (card back) is required.' });
    }

    const card = FlashcardsRepo.insertOne({
      _id: 'card_' + Math.random().toString(36).substring(2, 9) + Date.now().toString(36),
      deckId: deck._id,
      userId: req.user!._id,
      question: question.trim(),
      answer: answer.trim(),
      explanation: (explanation || '').trim(),
      example: (example || '').trim(),
      subjectId: deck.subjectId,
      topicId: deck.topicId,
      difficulty: ['easy', 'medium', 'hard'].includes(difficulty) ? difficulty : 'medium',
      box: 0,
      reviewCount: 0,
      nextReviewDate: new Date().toISOString(),
      learned: false,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    });

    const newCount = FlashcardsRepo.count(c => c.deckId === deck._id);
    FlashcardDecksRepo.updateById(deck._id, { cardCount: newCount, updatedAt: new Date().toISOString() });

    // Sync to MongoDB Atlas if connected
    if (mongoose.connection.readyState === 1) {
      try {
        await MongoFlashcardModel.create({
          _id: card._id,
          deckId: card.deckId,
          userId: card.userId,
          question: card.question,
          answer: card.answer,
          explanation: card.explanation,
          example: card.example,
          subjectId: card.subjectId,
          topicId: card.topicId,
          difficulty: card.difficulty,
          box: card.box,
          reviewCount: card.reviewCount,
          nextReviewDate: card.nextReviewDate,
          learned: card.learned,
        });
        await MongoFlashcardDeckModel.updateOne(
          { _id: deck._id },
          { $set: { cardCount: newCount, updatedAt: new Date().toISOString() } }
        );
      } catch (mongoErr) {
        console.warn('[MongoDB Atlas] Sync error on add card:', mongoErr);
      }
    }

    res.status(201).json({ success: true, data: { card } });
  } catch (err) {
    next(err);
  }
});

// POST /api/flashcards/cards/:id/review (Spaced Repetition Review)
router.post('/cards/:id/review', authenticate, (req: AuthenticatedRequest, res, next) => {
  try {
    const card = FlashcardsRepo.findById(req.params.id);
    if (!card || card.userId !== req.user!._id) {
      return res.status(404).json({ success: false, error: 'Card not found.' });
    }

    const { rating } = req.body; // 'again' | 'hard' | 'good' | 'easy'
    if (!['again', 'hard', 'good', 'easy'].includes(rating)) {
      return res.status(400).json({ success: false, error: 'Invalid rating. Expected: again, hard, good, or easy.' });
    }

    let newBox = card.box;
    let daysToAdd = 1;

    switch (rating) {
      case 'again':
        newBox = 0;
        daysToAdd = 0; // Due immediately / today
        break;
      case 'hard':
        newBox = Math.max(0, card.box);
        daysToAdd = 1;
        break;
      case 'good':
        newBox = Math.min(5, card.box + 1);
        daysToAdd = Math.pow(2, newBox); // 2, 4, 8, 16, 32 days
        break;
      case 'easy':
        newBox = Math.min(5, card.box + 2);
        daysToAdd = Math.pow(2, newBox) + 2;
        break;
    }

    const nextDate = new Date();
    nextDate.setDate(nextDate.getDate() + daysToAdd);

    const updated = FlashcardsRepo.updateById(card._id, {
      box: newBox,
      reviewCount: (card.reviewCount || 0) + 1,
      lastReviewedAt: new Date().toISOString(),
      nextReviewDate: nextDate.toISOString(),
      learned: newBox >= 3,
    });

    // Record review log
    FlashcardReviewsRepo.insertOne({
      _id: 'rev_' + Date.now().toString(36),
      userId: req.user!._id,
      deckId: card.deckId,
      flashcardId: card._id,
      rating: rating as any,
      reviewedAt: new Date().toISOString(),
    });

    // Update progress
    if (card.subjectId) {
      const prog = ProgressRepo.findOne(p => p.userId === req.user!._id && p.subjectId === card.subjectId);
      if (prog) {
        ProgressRepo.updateById(prog._id, {
          flashcardsReviewed: (prog.flashcardsReviewed || 0) + 1,
          lastStudiedAt: new Date().toISOString(),
        });
      }
    }

    res.json({ success: true, data: { card: updated } });
  } catch (err) {
    next(err);
  }
});

// DELETE /api/flashcards/cards/:id
router.delete('/cards/:id', authenticate, (req: AuthenticatedRequest, res, next) => {
  try {
    const card = FlashcardsRepo.findById(req.params.id);
    if (!card || card.userId !== req.user!._id) {
      return res.status(404).json({ success: false, error: 'Card not found.' });
    }

    FlashcardsRepo.deleteById(card._id);
    const newCount = FlashcardsRepo.count(c => c.deckId === card.deckId);
    FlashcardDecksRepo.updateById(card.deckId, { cardCount: newCount });

    res.json({ success: true, message: 'Card deleted.' });
  } catch (err) {
    next(err);
  }
});

// DELETE /api/flashcards/decks/:id
router.delete('/decks/:id', authenticate, (req: AuthenticatedRequest, res, next) => {
  try {
    const deck = FlashcardDecksRepo.findById(req.params.id);
    if (!deck || deck.userId !== req.user!._id) {
      return res.status(404).json({ success: false, error: 'Deck not found.' });
    }

    FlashcardDecksRepo.deleteById(deck._id);
    FlashcardsRepo.deleteMany(c => c.deckId === deck._id);

    res.json({ success: true, message: 'Deck and cards deleted.' });
  } catch (err) {
    next(err);
  }
});

export default router;
